import zlib from "node:zlib";
import "./env.mjs";
import { startInstance, call } from "./common.mjs";
const ok = (c, m) => { console.log(`${c ? "PASS" : "FAIL"}  ${m}`); if (!c) process.exitCode = 1; };
const A = await startInstance(5195, "a");
await call(A.base, "GET", "/api/config");
const blob = globalThis.__sharedBlobStore;
const ist = (ms) => new Date(ms).toLocaleDateString("en-CA", { timeZone: "Asia/Kolkata" });
blob.set(`gradex-backups/${ist(Date.now() - 15 * 864e5)}.json.gz`, { buf: Buffer.from("old"), etag: '"x"' });
blob.set(`gradex-backups/${ist(Date.now() - 10 * 864e5)}.json.gz`, { buf: Buffer.from("recent"), etag: '"y"' });
ok((await call(A.base, "GET", "/api/cron/reminders")).status === 401, "the job refuses callers without the cron secret");
const run = await call(A.base, "GET", "/api/cron/reminders", { headers: { authorization: "Bearer cron-test-secret" } });
ok(run.status === 200 && run.body.backup?.day === ist(Date.now()), `the daily job ran and backed up (${JSON.stringify(run.body.backup?.rows ?? run.body)})`);
const saved = blob.get(`gradex-backups/${ist(Date.now())}.json.gz`);
const parsed = saved && JSON.parse(zlib.gunzipSync(saved.buf).toString());
ok(parsed?.tables?.Users?.length > 0 && Object.keys(parsed.tables).length === 8, `today's backup holds every table (${parsed?.tables?.Users?.length} people)`);
ok(!blob.has(`gradex-backups/${ist(Date.now() - 15 * 864e5)}.json.gz`), "the 15-day-old backup was removed");
ok(blob.has(`gradex-backups/${ist(Date.now() - 10 * 864e5)}.json.gz`), "backups within 14 days are kept");
const again = await call(A.base, "GET", "/api/cron/reminders", { headers: { authorization: "Bearer cron-test-secret" } });
ok(again.status === 200, "running twice in a day just refreshes today's copy");
A.server.close(); globalThis.__fakeUpstash.server.close(); process.exit();
